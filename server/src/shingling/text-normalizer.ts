// Нормализация текста перед шинглированием: убираем пунктуацию и лишние
// пробелы, приводим к нижнему регистру — иначе два одинаковых по смыслу
// куска текста, отличающихся только знаками препинания или регистром,
// дадут разные шинглы и заимствование не будет найдено.
export function normalizeToWords(text: string): string[] {
  return (
    text
      .toLowerCase()
      .match(/[\p{L}\p{N}]+/gu) ?? []
  );
}
